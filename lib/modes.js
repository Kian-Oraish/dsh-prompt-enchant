export function modeIds() {
  return MODE_IDS
}

export function hasMode(id) {
  return typeof id === 'string' && MODE_IDS.includes(id) && MODES[id] !== undefined
}

export function defaultMode() {
  return MODE_IDS[0]
}

// 组装某模式的完整系统提示词;未知模式返回 undefined
export function buildSystemPrompt(modeId) {
  if (!hasMode(modeId)) return undefined
  return [CORE_A, MODES[modeId].layer, CORE_B].join('\n\n')
}

// 面向设置卡片 / API 的公开元数据(绝不含提示词正文)
export function publicModes() {
  return MODE_IDS.map((id) => {
    const m = MODES[id]
    return { id, name: m.name, description: m.description, tags: m.tags }
  })
}

// 诊断用:共享核心指纹(核心段被改动时指纹变化,便于排查行为漂移)
export function coreFingerprint() {
  return CORE_A.length + ':' + CORE_B.length + ':' + CORE_A.length + CORE_B.length
}
